import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('public/wiki.html','utf8');
const section=(html.match(/<section\b[^>]*id="tb-wiki-seo-overview"[^>]*>[\s\S]*?<\/section>/i)||[])[0]||'';
assert(section,'Wiki overview missing after build');
assert.equal((html.match(/id="tb-wiki-seo-overview"/g)||[]).length,1,'Wiki overview must be unique');
assert(section.includes('Tra cứu vũ khí, phụ kiện, phương tiện và bản đồ PUBG Mobile'),'topic heading absent');
for(const subject of ['Vũ khí PUBG Mobile','Phụ kiện PUBG Mobile','Phương tiện PUBG Mobile','Bản đồ PUBG Mobile']) assert(section.includes('<h3>'+subject+'</h3>'),'Wiki category absent: '+subject);
for(const dest of ['/ban-cap-nhat','/news','#catalog'])assert(section.includes('href="'+dest+'"'),'Missing canonical internal link '+dest);
assert(section.includes('nguồn đối chiếu, phiên bản và trạng thái xác minh'),'Evidence caveat absent');
assert(!section.includes('href="/updates"'),'Legacy noindex URL linked');
assert(html.includes('href="/seo11d-wiki-overview.css?v=1"'),'Overview CSS absent');
assert.equal((html.match(/<h1\b/gi)||[]).length,1,'Existing Wiki H1 changed');
assert(html.includes('id="catalog"'),'Existing Wiki catalog missing');
const head=html.slice(0,html.indexOf('</head>'));
assert(head.includes('rel="canonical"')&&head.includes('https://trainingbot.io.vn/wiki'),'Canonical changed');
assert(!/<meta\b[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(head),'Canonical Wiki noindexed');
const styles=fs.readFileSync('public/seo11d-wiki-overview.css','utf8');
assert(styles.includes('max-width:690px'),'Mobile responsive overview missing');
assert(fs.existsSync('public/admin.html'),'Admin unavailable');
console.log('SEO-11.D PASS: four crawlable categories, caveats, canonical links, preserved H1/catalog and responsive CSS');
