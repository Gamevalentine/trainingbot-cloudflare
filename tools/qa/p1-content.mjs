
import assert from "node:assert/strict";
import fs from "node:fs";
const read=p=>fs.readFileSync(p,"utf8");
const wiki=read("public/wiki.html"),compare=read("public/wiki_compare_p1.js");
assert(wiki.includes('id="tbP1Compare"')&&wiki.includes('id="tbP1First"')&&wiki.includes('id="tbP1Second"'));
assert(wiki.includes("pubgm.vnggames.com"));
assert(compare.includes("Nguồn riêng: chưa ghi nhận")&&compare.includes("Ngày kiểm chứng: chưa có"));
assert(read("public/news.html").includes('href="/ban-cap-nhat"'));
assert(read("public/robots.txt").includes("https://trainingbot.io.vn/sitemap-posts.xml"));
assert(read("public/sitemap.xml").includes("https://trainingbot.io.vn/"));
const code=read("functions/bai-viet/[slug].js");
const {onRequestGet}=await import("data:text/javascript;base64,"+Buffer.from(code).toString("base64"));
const post={slug:"qa-news-test",title:"Bài đăng kiểm thử",summary:"Một tóm tắt độc lập đã được biên soạn.",category:"Tin mới",content:"## Giới thiệu\nĐọc nguồn: https://www.pubgmobile.com/en/event/260Devnotes/.",rich_content:"",cover_url:"/news-pubg-mobile-4-6-cover.webp",published_at:"2026-10-20T00:00:00Z",updated_at:"2026-10-21T00:00:00Z"};
const mock={prepare(sql){return {bind(){return this;},async run(){return {success:true}},async all(){return {results:sql.includes("PRAGMA")?[{name:"featured_at"},{name:"rich_content"}]:sql.includes("SELECT slug,title FROM")?[{slug:"other-news",title:"Bài liên quan"}]:[]}},async first(){return post}}}};
const response=await onRequestGet({env:{DB:mock},params:{slug:post.slug}});
assert.equal(response.status,200);
const html=await response.text();
assert(html.includes("<h2>Giới thiệu</h2>"));
assert(html.includes("Nguồn được bài viết dẫn"));
assert(html.includes('href="https://www.pubgmobile.com/en/event/260Devnotes/"'));
assert(html.includes('href="/bai-viet/other-news"'));
assert(html.includes('rel="canonical" href="https://trainingbot.io.vn/bai-viet/qa-news-test"'));
assert(html.includes("application/ld+json"));
assert(html.includes('name="description" content="Một tóm tắt độc lập đã được biên soạn."'));
const noSrc={...post,summary:"",content:"Bài viết không có liên kết nguồn."};
const empty={prepare(sql){return {bind(){return this;},async run(){return {success:true}},async all(){return {results:sql.includes("PRAGMA")?[{name:"featured_at"},{name:"rich_content"}]:[]}},async first(){return noSrc}}}};
const res=await onRequestGet({env:{DB:empty},params:{slug:post.slug}});
const page=await res.text();
assert(page.includes("<h2>Nội dung bài viết</h2>"));
assert(page.includes("Chưa có liên kết nguồn trực tiếp"));
assert(page.includes('name="description" content="Bài viết không có liên kết nguồn."'));
console.log("P1 Wiki provenance and compare, article headings/sources/related, canonical/sitemap: PASS");
